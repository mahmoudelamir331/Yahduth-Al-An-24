-- ---------------------------------------------------------------------------
-- إضافة عمود image_caption لوصف صورة الغلاف
--
-- بدل ما الواجهة تعرض نص ثابت ("صورة صحفية حقيقية عالية الجودة") تحت كل
-- صورة، بقى الموظف يتحكم في النص من لوحة الإدارة، وللمحرّكين في
-- صورة الغلاف (alt text + الوصف الظاهر تحت الصورة) بتتحقق SEO.
-- ---------------------------------------------------------------------------

alter table public.articles
  add column if not exists image_caption text;

comment on column public.articles.image_caption is
  'وصف صورة الغلاف: النص البديل (alt) والوصف الظاهر تحت الصورة في صفحة الخبر';
