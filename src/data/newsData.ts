export function getArticlesByCategory(categorySlug: string): Article[] {
  if (!categorySlug || categorySlug === "all") return ALL_NEWS;
  return ALL_NEWS.filter((art) => art.categorySlug === categorySlug || art.category.includes(categorySlug));
}
